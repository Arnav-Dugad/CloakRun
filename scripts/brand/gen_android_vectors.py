#!/usr/bin/env python3
"""Generate Android VectorDrawables from the CloakRun brand sources.

Source of truth: branding/cloakrun-icon.svg and branding/cloakrun-logo.svg.
The geometry below is transcribed 1:1 from cloakrun-icon.svg (same coordinates,
same gradients, same opacities). Only format adaptations are applied:

- SVG feGaussianBlur (not supported by VectorDrawable) becomes a soft radial gradient.
- The rounded frame is dropped for adaptive layers because the launcher applies its own mask.
- Adaptive and splash layers use a 1536 viewport with the 1024 artwork centred, so the
  original canvas maps exactly onto the 72dp visible area of a 108dp adaptive icon
  (and onto the 192dp visible circle of a 288dp splash icon).

Run from the repo root: python scripts/brand/gen_android_vectors.py
"""
from __future__ import annotations

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
ICON_SVG = ROOT / "branding" / "cloakrun-icon.svg"
LOGO_SVG = ROOT / "branding" / "cloakrun-logo.svg"

APP_RES = ROOT / "app" / "src" / "main" / "res"
DS_RES = ROOT / "core" / "designsystem" / "src" / "main" / "res"

HEADER = "<!-- Generated by scripts/brand/gen_android_vectors.py from branding/. Do not edit by hand. -->\n"
NS = (
    'xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt" '
    'xmlns:tools="http://schemas.android.com/tools"'
)
# Brand vectors are drawn once (launch, About) and are rasterised to a cached bitmap by the framework,
# so the lint size and path-length heuristics for frequently drawn icons do not apply to them.
BRAND_IGNORE = ' tools:ignore="VectorRaster,VectorPath"'


def round_path(d: str) -> str:
    """Rounds every number in SVG path data to one decimal place (sub-pixel at any rendered size)."""
    return re.sub(r"-?\d+\.\d+", lambda m: f"{float(m.group()):.1f}".rstrip("0").rstrip("."), d)


def argb(hex_rgb: str, opacity: float = 1.0) -> str:
    hex_rgb = hex_rgb.lstrip("#")
    a = max(0, min(255, round(opacity * 255)))
    return f"#{a:02X}{hex_rgb.upper()}"


def stops_xml(stops: list[tuple[float, str, float]]) -> str:
    return "".join(
        f'<item android:offset="{o}" android:color="{argb(c, a)}"/>' for o, c, a in stops
    )


def linear(attr: str, x1, y1, x2, y2, stops) -> str:
    return (
        f'<aapt:attr name="android:{attr}"><gradient android:type="linear" '
        f'android:startX="{x1}" android:startY="{y1}" android:endX="{x2}" android:endY="{y2}">'
        f"{stops_xml(stops)}</gradient></aapt:attr>"
    )


def radial(attr: str, cx, cy, r, stops) -> str:
    return (
        f'<aapt:attr name="android:{attr}"><gradient android:type="radial" '
        f'android:centerX="{cx}" android:centerY="{cy}" android:gradientRadius="{r}">'
        f"{stops_xml(stops)}</gradient></aapt:attr>"
    )


def circle(cx, cy, r) -> str:
    return f"M{cx - r},{cy} a{r},{r} 0 1,0 {2 * r},0 a{r},{r} 0 1,0 {-2 * r},0 Z"


def rrect(x, y, w, h, r) -> str:
    return (
        f"M{x + r},{y} H{x + w - r} A{r},{r} 0 0 1 {x + w},{y + r} V{y + h - r} "
        f"A{r},{r} 0 0 1 {x + w - r},{y + h} H{x + r} A{r},{r} 0 0 1 {x},{y + h - r} "
        f"V{y + r} A{r},{r} 0 0 1 {x + r},{y} Z"
    )


def path(d: str, *, fill: str | None = None, fill_grad: str = "", stroke: str | None = None,
         stroke_grad: str = "", width: float | None = None, fill_alpha: float | None = None,
         stroke_alpha: float | None = None, cap: str | None = None, name: str | None = None,
         fill_type: str | None = None, trim_end: float | None = None) -> str:
    attrs = [f'android:pathData="{d}"']
    if name:
        attrs.append(f'android:name="{name}"')
    if fill:
        attrs.append(f'android:fillColor="{fill}"')
    if stroke:
        attrs.append(f'android:strokeColor="{stroke}"')
    if width is not None:
        attrs.append(f'android:strokeWidth="{width}"')
    if fill_alpha is not None:
        attrs.append(f'android:fillAlpha="{fill_alpha}"')
    if stroke_alpha is not None:
        attrs.append(f'android:strokeAlpha="{stroke_alpha}"')
    if cap:
        attrs.append(f'android:strokeLineCap="{cap}"')
    if fill_type:
        attrs.append(f'android:fillType="{fill_type}"')
    if trim_end is not None:
        attrs.append(f'android:trimPathEnd="{trim_end}"')
    inner = fill_grad + stroke_grad
    if inner:
        return f"<path {' '.join(attrs)}>{inner}</path>"
    return f"<path {' '.join(attrs)}/>"


# ---------------------------------------------------------------- icon geometry (from SVG)
CLOAK = "M512,800 C430,700 322,600 322,440 A190,190 0 0 1 702,440 C702,600 594,700 512,800Z"
HOOD = "M512,575 C466,535 408,495 408,440 A104,104 0 0 1 616,440 C616,495 558,535 512,575Z"
FRAME = rrect(0, 0, 1024, 1024, 228)
HIGHLIGHT = "M0,0H1024V400C800,310 224,310 0,400Z"
ARC_CYAN = "M262,440 A250,250 0 0 1 512,190"
ARC_VIOLET = "M762,440 A250,250 0 0 1 512,690"

BG_STOPS = [(0, "1D1157", 1), (0.55, "0E0A2B", 1), (1, "060514", 1)]
AURA_STOPS = [(0, "7C5CFF", 0.60), (0.5, "3B2BB8", 0.24), (1, "3B2BB8", 0)]
CLOAK_STOPS = [(0, "F6F3FF", 1), (0.30, "BBAAFF", 1), (0.58, "7358F6", 1), (0.76, "5A41E0", 0.55),
               (0.92, "4A34C8", 0.12), (1, "3322B0", 0)]
RIM_STOPS = [(0, "FFFFFF", 0.95), (0.45, "FFFFFF", 0.35), (0.65, "FFFFFF", 0.12), (0.9, "FFFFFF", 0)]
SPEC_STOPS = [(0, "FFFFFF", 0.65), (1, "FFFFFF", 0)]
VOID_STOPS = [(0, "04030D", 1), (1, "1A0F4A", 1)]
EYE_GLOW_STOPS = [(0, "5CF2FF", 0.75), (1, "5CF2FF", 0)]
EYE_BLUR_STOPS = [(0, "5CF2FF", 0.9), (0.62, "5CF2FF", 0.75), (1, "5CF2FF", 0)]
ARC_CYAN_STOPS = [(0, "5CF2FF", 0), (1, "5CF2FF", 0.95)]
ARC_VIOLET_STOPS = [(0, "A48CFF", 0), (1, "A48CFF", 0.9)]
FRAME_RIM_STOPS = [(0, "FFFFFF", 0.38), (0.5, "FFFFFF", 0.04), (1, "FFFFFF", 0.12)]

VIOLET_PIXELS = [(520, 742, 26, 7, .85), (556, 772, 20, 6, .75), (498, 800, 16, 5, .70), (590, 806, 14, 4, .60),
                 (540, 836, 12, 4, .50), (628, 842, 10, 3, .42), (574, 872, 9, 3, .34), (500, 858, 8, 2.5, .30),
                 (668, 880, 7, 2, .24), (610, 908, 6, 2, .18), (540, 914, 6, 2, .15), (700, 918, 5, 1.5, .12)]
CYAN_PIXELS = [(588, 758, 12, 4, .70), (470, 772, 9, 3, .55), (640, 816, 8, 2.5, .40), (520, 888, 7, 2, .28)]


def background_body(extend: bool) -> str:
    full = "M-256,-256 H1280 V1280 H-256 Z" if extend else "M0,0 H1024 V1024 H0 Z"
    out = [
        path(full, fill_grad=linear("fillColor", 140, 0, 880, 1024, BG_STOPS)),
        path(full, fill_grad=radial("fillColor", 512, 470, 480, AURA_STOPS)),
        path(HIGHLIGHT, fill="#FFFFFFFF", fill_alpha=0.035),
    ]
    out += rings_and_arcs()
    return "".join(out)


def rings_and_arcs(names: bool = False) -> list[str]:
    return [
        path(circle(512, 440, 250), stroke="#FFFFFFFF", width=2, stroke_alpha=0.10),
        path(circle(512, 440, 340), stroke="#FFFFFFFF", width=2, stroke_alpha=0.07),
        path(circle(512, 440, 430), stroke="#FFFFFFFF", width=2, stroke_alpha=0.05),
        path(ARC_CYAN, stroke_grad=linear("strokeColor", 262, 440, 512, 190, ARC_CYAN_STOPS), width=10,
             cap="round", name="arc_cyan" if names else None),
        path(ARC_VIOLET, stroke_grad=linear("strokeColor", 762, 440, 512, 690, ARC_VIOLET_STOPS), width=10,
             cap="round", name="arc_violet" if names else None),
    ]


def cloak_parts(names: bool = False, hidden: bool = False) -> list[str]:
    spec = (
        '<group android:rotation="28" android:pivotX="420" android:pivotY="350">'
        '<group android:scaleX="0.4915" android:pivotX="420" android:pivotY="350">'
        + path(circle(420, 350, 118), fill_grad=radial("fillColor", 420, 350, 118, SPEC_STOPS),
               name="spec" if names else None, fill_alpha=0 if hidden else None)
        + "</group></group>"
    )
    return [
        path(CLOAK, fill_grad=linear("fillColor", 330, 250, 560, 840, CLOAK_STOPS),
             name="cloak_fill" if names else None, fill_alpha=0 if hidden else None),
        path(CLOAK, stroke_grad=linear("strokeColor", 330, 250, 560, 840, RIM_STOPS), width=4,
             name="cloak_rim" if names else None, trim_end=0 if hidden else None, cap="round"),
        spec,
        path(HOOD, fill_grad=linear("fillColor", 512, 336, 512, 575, VOID_STOPS),
             name="hood" if names else None, fill_alpha=0 if hidden else None),
        path(HOOD, stroke="#FFFFFFFF", stroke_alpha=0.18, width=2, name="hood_rim" if names else None,
             trim_end=0 if hidden else None),
    ]


def eye_parts() -> list[str]:
    return [
        path(circle(512, 446, 110), fill_grad=radial("fillColor", 512, 446, 110, EYE_GLOW_STOPS)),
        path(circle(512, 446, 64), stroke="#FF5CF2FF", stroke_alpha=0.40, width=3),
        path(circle(512, 446, 92), stroke="#FF5CF2FF", stroke_alpha=0.16, width=3),
        path(circle(512, 446, 42), fill_grad=radial("fillColor", 512, 446, 42, EYE_BLUR_STOPS)),
        path(circle(512, 446, 26), fill="#FFC9FBFF"),
        path(circle(505, 438, 8), fill="#FFFFFFFF", fill_alpha=0.9),
    ]


def pixel_parts() -> list[str]:
    out = [path(rrect(x, y, s, s, r), fill="#FFA48CFF", fill_alpha=a) for x, y, s, r, a in VIOLET_PIXELS]
    out += [path(rrect(x, y, s, s, r), fill="#FF5CF2FF", fill_alpha=a) for x, y, s, r, a in CYAN_PIXELS]
    return out


def vector(width_dp: int, viewport: int, body: str, name: str | None = None) -> str:
    n = f' android:name="{name}"' if name else ""
    return (
        f'{HEADER}<vector {NS}{BRAND_IGNORE}{n} android:width="{width_dp}dp" android:height="{width_dp}dp" '
        f'android:viewportWidth="{viewport}" android:viewportHeight="{viewport}">{body}</vector>\n'
    )


def centred(body: str, name: str | None = None) -> str:
    n = f' android:name="{name}"' if name else ""
    return f'<group{n} android:translateX="256" android:translateY="256">{body}</group>'


# ---------------------------------------------------------------- outputs
def adaptive_background() -> str:
    return vector(108, 1536, centred(background_body(extend=True)))


def adaptive_foreground() -> str:
    return vector(108, 1536, centred("".join(cloak_parts() + eye_parts() + pixel_parts())))


def adaptive_monochrome() -> str:
    # Themed icons use alpha only. Cloak silhouette with the hood opening cut out, the eye core
    # inside the hood, and the leading dissolve pixels.
    body = path(CLOAK + " " + HOOD, fill="#FFFFFFFF", fill_type="evenOdd")
    body += path(circle(512, 446, 30), fill="#FFFFFFFF")
    body += "".join(path(rrect(x, y, s, s, r), fill="#FFFFFFFF", fill_alpha=min(1.0, a + 0.15))
                    for x, y, s, r, a in VIOLET_PIXELS[:6])
    return vector(108, 1536, centred(body))


def emblem() -> str:
    body = (
        f'<clip-path android:pathData="{FRAME}"/>'
        + background_body(extend=False)
        + "".join(cloak_parts() + eye_parts() + pixel_parts())
    )
    rim = path(rrect(2, 2, 1020, 1020, 226),
               stroke_grad=linear("strokeColor", 0, 0, 1024, 1024, FRAME_RIM_STOPS), width=4)
    return vector(96, 1024, f"<group>{body}</group>{rim}")


def splash_static() -> str:
    # Pre-Android 12 (compat) splash: the full emblem without the frame, on the splash colour.
    body = "".join(rings_and_arcs() + cloak_parts() + eye_parts() + pixel_parts())
    return vector(288, 1536, centred(body))


def splash_animated() -> str:
    """Android 12+ animated splash icon (AnimatedVectorDrawable, 900ms total).

    0-520ms   cloak outline strokes draw on (trimPathEnd)
    260-760ms cloak fills in, hood opens
    420-820ms signal eye scales up with overshoot
    0-900ms   radar ring expands and the arcs sweep a quarter turn
    """
    rings = (
        '<group android:name="rings" android:pivotX="512" android:pivotY="440" '
        'android:scaleX="0.6" android:scaleY="0.6">'
        + "".join(rings_and_arcs(names=True)) + "</group>"
    )
    eye = (
        '<group android:name="eye" android:pivotX="512" android:pivotY="446" '
        'android:scaleX="0" android:scaleY="0">' + "".join(eye_parts()) + "</group>"
    )
    pixels = '<group android:name="pixels" android:translateY="40">' + "".join(pixel_parts()) + "</group>"
    drawable = centred(rings + "".join(cloak_parts(names=True, hidden=True)) + eye + pixels)
    vec = (
        f'<vector android:width="288dp" android:height="288dp" android:viewportWidth="1536" '
        f'android:viewportHeight="1536">{drawable}</vector>'
    )

    def anim(target: str, animators: str) -> str:
        return (
            f'<target android:name="{target}"><aapt:attr name="android:animation">'
            f'<set android:ordering="together">{animators}</set></aapt:attr></target>'
        )

    def oa(prop: str, frm, to, dur: int, delay: int = 0, interp: str = "fast_out_slow_in") -> str:
        return (
            f'<objectAnimator android:propertyName="{prop}" android:valueFrom="{frm}" android:valueTo="{to}" '
            f'android:duration="{dur}" android:startOffset="{delay}" android:valueType="floatType" '
            f'android:interpolator="@android:interpolator/{interp}"/>'
        )

    targets = "".join([
        anim("cloak_rim", oa("trimPathEnd", 0, 1, 520)),
        anim("hood_rim", oa("trimPathEnd", 0, 1, 420, 160)),
        anim("cloak_fill", oa("fillAlpha", 0, 1, 500, 260)),
        anim("hood", oa("fillAlpha", 0, 1, 400, 320)),
        anim("spec", oa("fillAlpha", 0, 1, 360, 520)),
        anim("eye", oa("scaleX", 0, 1, 400, 420, "overshoot") + oa("scaleY", 0, 1, 400, 420, "overshoot")),
        anim("rings", oa("scaleX", 0.6, 1, 900, 0, "decelerate_cubic")
             + oa("scaleY", 0.6, 1, 900, 0, "decelerate_cubic")
             + oa("rotation", -90, 0, 900, 0, "decelerate_cubic")),
        anim("pixels", oa("translateY", 40, 0, 600, 300, "decelerate_cubic")),
    ])
    return (
        f'{HEADER}<animated-vector {NS}{BRAND_IGNORE}><aapt:attr name="android:drawable">{vec}</aapt:attr>'
        f"{targets}</animated-vector>\n"
    )


def wordmark() -> str:
    """The CloakRun wordmark, rule and ARNAV GAMES line from the lockup, cropped to its bounds."""
    svg = LOGO_SVG.read_text(encoding="utf-8")
    paths = re.findall(r'<path d="([^"]+)" fill="url\(#(wordFill|subFill)\)"/>', svg)
    if len(paths) != 2:
        raise SystemExit("Could not find wordmark paths in cloakrun-logo.svg")
    word_d = round_path(next(d for d, f in paths if f == "wordFill"))
    sub_d = round_path(next(d for d, f in paths if f == "subFill"))
    word_stops = [(0, "FFFFFF", 1), (1, "C9BDFF", 1)]
    sub_stops = [(0, "5CF2FF", 1), (1, "A48CFF", 1)]
    rule_stops = [(0, "5CF2FF", 0.9), (1, "A48CFF", 0)]
    body = (
        '<group android:translateX="-650" android:translateY="-180">'
        + path(word_d, fill_grad=linear("fillColor", 650, 190, 650, 320, word_stops))
        + path(rrect(656, 360, 870, 3, 1.5), fill_grad=linear("fillColor", 656, 0, 1526, 0, rule_stops))
        + path(sub_d, fill_grad=linear("fillColor", 656, 0, 1148, 0, sub_stops))
        + "</group>"
    )
    return (
        f'{HEADER}<vector {NS}{BRAND_IGNORE} android:width="264dp" android:height="75dp" '
        f'android:viewportWidth="880" android:viewportHeight="250">{body}</vector>\n'
    )


def outlined_text(text: str, weight: int, tracking_em: float) -> tuple[str, float, float, float]:
    """Outlines [text] with Inter at [weight] into SVG path data (y down, baseline at ascender).

    Returns (path data, width, cap bottom, cap top) in font units. Requires fontTools.
    """
    from fontTools.pens.svgPathPen import SVGPathPen
    from fontTools.pens.transformPen import TransformPen
    from fontTools.ttLib import TTFont
    from fontTools.varLib.instancer import instantiateVariableFont

    font_path = DS_RES / "font" / "inter_variable.ttf"
    font = instantiateVariableFont(TTFont(font_path), {"wght": weight, "opsz": 14})
    cmap = font.getBestCmap()
    glyphs = font.getGlyphSet()
    upm = font["head"].unitsPerEm
    ascent = font["hhea"].ascent
    cap = font["OS/2"].sCapHeight
    pen = SVGPathPen(glyphs, ntos=lambda v: f"{v:.1f}".rstrip("0").rstrip("."))
    x = 0.0
    tracking = tracking_em * upm
    for i, ch in enumerate(text):
        name = cmap[ord(ch)]
        tpen = TransformPen(pen, (1, 0, 0, -1, x, ascent))
        glyphs[name].draw(tpen)
        x += glyphs[name].width + (tracking if i < len(text) - 1 else 0)
    top = ascent - cap
    return pen.getCommands(), x, float(top + cap), float(top)


def splash_branding() -> str:
    """Android 12+ splash branding image: "MADE BY ARNAV GAMES" in Inter SemiBold, tracked out."""
    d, width, bottom, top = outlined_text("MADE BY ARNAV GAMES", 600, 0.22)
    height = bottom - top
    pad_x = width * 0.04
    vw = width + 2 * pad_x
    vh = vw * 80 / 200
    stops = [(0, "5CF2FF", 0.92), (1, "A48CFF", 0.92)]
    body = (
        f'<group android:translateX="{pad_x:.1f}" android:translateY="{(vh - height) / 2 - top:.1f}">'
        + path(d, fill_grad=linear("fillColor", 0, 0, width, 0, stops))
        + "</group>"
    )
    # Exactly the 200x80dp branding slot, with the line of text centred vertically.
    return (
        f'{HEADER}<vector {NS}{BRAND_IGNORE} android:width="200dp" android:height="80dp" '
        f'android:viewportWidth="{vw:.1f}" android:viewportHeight="{vh:.1f}">{body}</vector>\n'
    )


ADAPTIVE = (
    '<?xml version="1.0" encoding="utf-8"?>\n' + HEADER
    + '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
    '    <background android:drawable="@drawable/ic_launcher_background" />\n'
    '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
    '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n'
    "</adaptive-icon>\n"
)


def write(p: pathlib.Path, text: str) -> None:
    p.parent.mkdir(parents=True, exist_ok=True)
    if not text.startswith("<?xml"):
        text = '<?xml version="1.0" encoding="utf-8"?>\n' + text
    p.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", p.relative_to(ROOT))


def main() -> None:
    if not ICON_SVG.exists():
        raise SystemExit(f"missing {ICON_SVG}")
    write(APP_RES / "drawable" / "ic_launcher_background.xml", adaptive_background())
    write(APP_RES / "drawable" / "ic_launcher_foreground.xml", adaptive_foreground())
    write(APP_RES / "drawable" / "ic_launcher_monochrome.xml", adaptive_monochrome())
    write(APP_RES / "mipmap-anydpi" / "ic_launcher.xml", ADAPTIVE)
    write(APP_RES / "mipmap-anydpi" / "ic_launcher_round.xml", ADAPTIVE)
    write(APP_RES / "drawable" / "splash_icon_static.xml", splash_static())
    write(APP_RES / "drawable-v31" / "splash_icon_animated.xml", splash_animated())
    write(DS_RES / "drawable" / "cr_emblem.xml", emblem())
    write(DS_RES / "drawable" / "cr_wordmark.xml", wordmark())
    write(APP_RES / "drawable-v31" / "splash_branding.xml", splash_branding())


if __name__ == "__main__":
    main()
